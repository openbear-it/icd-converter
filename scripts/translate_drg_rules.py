def translate(desc: str) -> str:
    result = desc
    # Sort longest phrases first so compound terms match before their components.
    for en, it in sorted(PHRASES, key=lambda x: -len(x[0])):
        # \b word boundaries prevent matching inside already-translated Italian words.
        pattern = re.compile(r'\b' + re.escape(en) + r'\b', re.IGNORECASE)
        result = pattern.sub(it, result)
    return result


def main():
    with open(IN_CSV, newline="", encoding="utf-8") as f:
        rows = list(csv.DictReader(f))
    fieldnames = list(rows[0].keys())

    changed = 0
    for row in rows:
        orig = row["description"]
        translated = translate(orig)
        if translated != orig:
            changed += 1
        row["description"] = translated

    with open(OUT_CSV, "w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=fieldnames)
        writer.writeheader()
        writer.writerows(rows)
    print(f"Done. {changed}/{len(rows)} descriptions translated → {OUT_CSV}")

    # Preview
    print("\nSample:")
    for row in rows[:10]:
        print(f"  {row['code']}: {row['description']}")


if __name__ == "__main__":
    main()
